#!/usr/bin/env node
// Fetches wordset-dictionary (MIT) and compiles chrome-extension/dict.js
// Usage: node scripts/build-dict.js

const https = require('https');
const fs    = require('fs');
const path  = require('path');

const BASE = 'https://raw.githubusercontent.com/wordset/wordset-dictionary/master/data/';
const OUT  = path.join(__dirname, '..', 'chrome-extension', 'dict.js');

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, res => {
      if (res.statusCode !== 200) { reject(new Error(`HTTP ${res.statusCode} for ${url}`)); return; }
      const chunks = [];
      res.on('data', c => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    }).on('error', reject);
  });
}

async function main() {
  const letters = 'abcdefghijklmnopqrstuvwxyz'.split('');
  const dict    = {};
  let   total   = 0;

  for (const letter of letters) {
    process.stdout.write(`  ${letter} `);
    try {
      const raw  = await get(`${BASE}${letter}.json`);
      const data = JSON.parse(raw);
      let n = 0;
      for (const [word, entry] of Object.entries(data)) {
        const m = entry.meanings?.[0];
        if (!m?.def) continue;
        const key = word.toLowerCase();
        // skip multi-word phrases
        if (key.includes(' ')) continue;
        const compact = { p: m.speech_part || '', d: m.def };
        if (m.example)            compact.e = m.example;
        if (m.synonyms?.length)   compact.s = m.synonyms.slice(0, 4);
        dict[key] = compact;
        n++; total++;
      }
      console.log(`${n}`);
    } catch (err) {
      console.log(`FAILED: ${err.message}`);
    }
  }

  const header = `// Local dictionary — generated by scripts/build-dict.js\n// Source: wordset-dictionary (MIT license, https://github.com/wordset/wordset-dictionary)\n// ${total} entries — do not edit manually\n`;
  const body   = `self.DICT=${JSON.stringify(dict)};\n`;
  fs.writeFileSync(OUT, header + body, 'utf8');

  const sizeMB = (fs.statSync(OUT).size / 1024 / 1024).toFixed(1);
  console.log(`\nWrote ${OUT}`);
  console.log(`  ${total.toLocaleString()} words · ${sizeMB} MB`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
